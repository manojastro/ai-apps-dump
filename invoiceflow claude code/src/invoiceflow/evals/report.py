"""Turn a baseline run into docs/BASELINE_REPORT.md plus a JSON evidence file.

Every number in the report comes from the run it describes; the header records the exact
command, time, git commit, dataset version and control-matrix version.
"""

import json
import subprocess
from collections.abc import Sequence
from datetime import UTC, datetime
from pathlib import Path

from invoiceflow.data.dataset import Dataset
from invoiceflow.data.models import ExceptionCode, Frozen
from invoiceflow.evals.baseline import CaseResult
from invoiceflow.evals.scoring import Rate, Summary
from invoiceflow.policy.matrix import ControlMatrix

# Scenarios a rule-only matcher cannot get right by design, and why. Anything else that
# shows up as an error is reported as unexpected.
KNOWN_LIMITS = {
    "adv_hidden_bank_change": "needs invoice text: the new account appears only in the notes",
    "price_escalation_within": "needs the contract: an escalation clause authorises the price",
}


class RunMeta(Frozen):
    command: str
    run_at: str
    git_commit: str
    git_clean: bool
    backend: str
    split: str
    dataset_version: str
    seed: int
    generator_version: str
    faker_version: str
    matrix_version: str


def _git(*args: str) -> str:
    result = subprocess.run(  # noqa: S603 - fixed git arguments, no user input
        ["git", *args],  # noqa: S607 - git from PATH is the developer's own tool
        capture_output=True,
        text=True,
        check=False,
    )
    return result.stdout.strip()


def run_meta(
    command: str, backend: str, split: str, dataset: Dataset, matrix: ControlMatrix
) -> RunMeta:
    return RunMeta(
        command=command,
        run_at=datetime.now(UTC).astimezone().isoformat(timespec="seconds"),
        git_commit=_git("rev-parse", "--short", "HEAD") or "unknown",
        git_clean=_git("status", "--porcelain") == "",
        backend=backend,
        split=split,
        dataset_version=dataset.version,
        seed=dataset.seed,
        generator_version=dataset.generator_version,
        faker_version=dataset.faker_version,
        matrix_version=matrix.version_hash,
    )


def _rate(rate: Rate) -> str:
    return f"{rate.correct} / {rate.total} ({rate.pct}%)"


def _fmt(value: object) -> str:
    return "n/a" if value is None else str(value)


SHORT_NAMES = {
    "CLEAN": "CLEAN",
    "PRICE_VARIANCE": "PRICE",
    "QTY_OVERBILLED": "QTY",
    "MISSING_GRN": "NO_GRN",
    "DUPLICATE_INVOICE": "DUP",
    "GST_MISMATCH": "GST",
    "PO_CLOSED": "PO",
    "VENDOR_BANK_CHANGE": "BANK",
}


def render_markdown(meta: RunMeta, summary: Summary) -> str:
    codes = [code.value for code in ExceptionCode]
    short = SHORT_NAMES
    lines = [
        f"# Baseline report: rule-only matcher ({meta.split} split)",
        "",
        f"> Generated by `{meta.command}` on {meta.run_at}. Do not edit by hand: re-run the",
        "> command. All data is synthetic.",
        "",
        "| Run metadata | |",
        "|---|---|",
        f"| Command | `{meta.command}` |",
        f"| Run at | {meta.run_at} |",
        f"| Git commit | `{meta.git_commit}` "
        f"({'clean' if meta.git_clean else 'uncommitted changes'}) |",
        f"| Dataset version | `{meta.dataset_version[:16]}` (seed {meta.seed}, generator "
        f"{meta.generator_version}, Faker {meta.faker_version}) |",
        f"| Control matrix version | `{meta.matrix_version[:16]}` |",
        f"| Backend | {meta.backend} |",
        f"| Split | {meta.split} ({summary.cases} invoices) |",
        "",
        "## Results",
        "",
        "| Metric | Result |",
        "|---|---|",
        f"| Exception classification accuracy | {_rate(summary.exception)} |",
        f"| Resolution action accuracy | {_rate(summary.action)} |",
        f"| Required approver accuracy | {_rate(summary.approver)} |",
        f"| Exception, action and approver all correct | {_rate(summary.all_three)} |",
        f"| Baseline proposals denied by policy | {summary.policy_denials} |",
        f"| Unsafe outcomes on adversarial invoices | {summary.adversarial_unsafe} of "
        f"{summary.adversarial_cases} |",
        "",
        "An unsafe outcome approves an invoice that should not be approved, or fails to "
        "escalate a suspected bank-detail fraud.",
        "",
        "## How to read these numbers",
        "",
        "The labels and the matcher both follow the same written rules (AP-POL and the",
        "approved Phase 1 interpretations), and the data is synthetic. High scores therefore",
        "show that the code implements the spec consistently. They are not evidence of",
        "accuracy on real invoices, which are messier than any generator. What matters here",
        "is where the baseline fails and why: those are the cases the agent must improve on.",
        "",
        "## Exception classes",
        "",
        "| Class | Support | Predicted | Correct | Precision | Recall |",
        "|---|---|---|---|---|---|",
    ]
    for score in summary.per_class:
        lines.append(
            f"| {score.label.value} | {score.support} | {score.predicted} | "
            f"{score.true_positive} | {_fmt(score.precision)} | {_fmt(score.recall)} |"
        )
    lines += [
        "",
        "## Confusion matrix",
        "",
        "Rows are the expected exception, columns the baseline's prediction.",
        "",
        "| Expected \\ Predicted | " + " | ".join(short[c] for c in codes) + " |",
        "|---|" + "---|" * len(codes),
    ]
    for expected in codes:
        row = summary.confusion[expected]
        lines.append(f"| {expected} | " + " | ".join(str(row[c]) for c in codes) + " |")
    lines += [
        "",
        "## Where the baseline is wrong",
        "",
        "Invoices where the exception, action or approver differs from the label, by scenario.",
        "",
    ]
    if summary.errors_by_scenario:
        lines += ["| Scenario | Invoices | Why |", "|---|---|---|"]
        for scenario, count in summary.errors_by_scenario.items():
            why = KNOWN_LIMITS.get(scenario, "**unexpected: investigate**")
            lines.append(f"| `{scenario}` | {count} | {why} |")
    else:
        lines.append("None.")
    lines += [
        "",
        "## What this baseline cannot do",
        "",
        "- It reads no free text, so it misses a bank change requested only in invoice notes.",
        "- It reads no contracts, so it cannot tell an authorised price escalation from an",
        "  overcharge.",
        "- Because it ignores invoice text, prompt injection cannot affect it. That says",
        "  nothing about how the LLM agent will behave; the agent is measured separately.",
        "",
    ]
    return "\n".join(lines)


def write_report(
    meta: RunMeta,
    summary: Summary,
    cases: Sequence[CaseResult],
    report_path: Path,
    evidence_path: Path,
) -> None:
    report_path.parent.mkdir(parents=True, exist_ok=True)
    report_path.write_text(render_markdown(meta, summary), encoding="utf-8", newline="\n")
    evidence_path.parent.mkdir(parents=True, exist_ok=True)
    evidence = {
        "meta": meta.model_dump(mode="json"),
        "summary": summary.model_dump(mode="json"),
        "cases": [case.model_dump(mode="json") for case in cases],
    }
    evidence_path.write_text(
        json.dumps(evidence, indent=2, sort_keys=True) + "\n", encoding="utf-8", newline="\n"
    )
