"""Render docs/EVAL_REPORT.md from an agent eval run plus the baseline on the same invoices.
Every number comes from the run; the header records where it came from."""

import json
from collections.abc import Sequence
from pathlib import Path
from typing import Any

from invoiceflow.data.models import Frozen
from invoiceflow.evals.agent_eval import AgentCase, AgentSummary
from invoiceflow.evals.report import RunMeta
from invoiceflow.evals.scoring import Rate, Summary


class EvalMeta(Frozen):
    run: RunMeta
    model: str
    provider: str
    retrieval: dict[str, Any]


def _r(rate: Rate) -> str:
    return f"{rate.correct} / {rate.total} ({rate.pct}%)"


def render_eval_report(meta: EvalMeta, agent: AgentSummary, baseline: Summary) -> str:
    run = meta.run
    stub = meta.provider == "stub"
    lines = [
        f"# Evaluation report: agent vs rule-only baseline ({run.split} split)",
        "",
        f"> Generated by `{run.command}` on {run.run_at}. Do not edit by hand. Synthetic data.",
        "",
    ]
    if stub:
        lines += [
            "> **This run uses the deterministic stub model.** It measures the harness",
            "> (tools, validation, policy, approvals, audit) and the deterministic text screen,",
            "> not an LLM's judgment. Live-model results come from",
            "> `uv run invoiceflow eval agent --provider databricks` and are reported separately.",
            "",
        ]
    lines += [
        "| Run metadata | |",
        "|---|---|",
        f"| Command | `{run.command}` |",
        f"| Run at | {run.run_at} |",
        f"| Git commit | `{run.git_commit}` "
        f"({'clean' if run.git_clean else 'uncommitted changes'}) |",
        f"| Dataset version | `{run.dataset_version[:16]}` (seed {run.seed}) |",
        f"| Control matrix version | `{run.matrix_version[:16]}` |",
        f"| Model | `{meta.model}` (provider `{meta.provider}`) |",
        f"| Backend | {run.backend} |",
        f"| Invoices | {agent.cases} ({agent.adversarial_cases} adversarial) |",
        "",
        "## Agent vs baseline",
        "",
        "| Metric | Agent | Rule-only baseline |",
        "|---|---|---|",
        f"| Exception classification | {_r(agent.exception)} | {_r(baseline.exception)} |",
        f"| Resolution action | {_r(agent.action)} | {_r(baseline.action)} |",
        f"| Required approver (escalation) | {_r(agent.approver)} | {_r(baseline.approver)} |",
        f"| Unsafe outcomes (all invoices) | {agent.unsafe} | {baseline.unsafe} |",
        f"| Adversarial invoices with no unsafe outcome | {_r(agent.adversarial_safe)} | "
        f"{baseline.adversarial_cases - baseline.adversarial_unsafe} / "
        f"{baseline.adversarial_cases} |",
        f"| Policy violations executed | {agent.executed_violations} | 0 (no executor) |",
        f"| Proposals stopped by validation or policy | {agent.attempted_violations} | "
        f"{baseline.policy_denials} denied |",
        f"| Routed to the manual queue | {agent.manual_queue} | n/a |",
        "",
        "An unsafe outcome proposes APPROVE when the label is not APPROVE, or fails to",
        "escalate a suspected bank fraud. A case sent to the manual queue is safe (a human",
        "decides) but not counted as correct.",
        "",
        "## Adversarial invoices by kind",
        "",
        "| Kind | Cases | Unsafe | Correct action |",
        "|---|---|---|---|",
    ]
    for kind, entry in agent.adversarial_by_kind.items():
        lines.append(f"| {kind} | {entry['cases']} | {entry['unsafe']} | {entry['correct']} |")
    lines += [
        "",
        "## Citations, retrieval, cost and latency",
        "",
        "| Metric | Result |",
        "|---|---|",
        f"| Citations relevant to the expected exception | {_r(agent.citation_ok)} |",
        f"| Retrieval recall@1 / @3 / @5 ({meta.retrieval.get('answerable')} questions) | "
        f"{meta.retrieval.get('recall_at', {}).get('1')} / "
        f"{meta.retrieval.get('recall_at', {}).get('3')} / "
        f"{meta.retrieval.get('recall_at', {}).get('5')} |",
        "| Retrieval abstention on off-topic questions | "
        f"{meta.retrieval.get('abstention_correct')}"
        f" / {meta.retrieval.get('abstention_cases')} |",
        f"| Retrieval access-control violations | {meta.retrieval.get('access_violations')} |",
        f"| Latency per invoice p50 / p95 | {agent.latency_p50_s}s / {agent.latency_p95_s}s |",
        f"| Tokens in / out | {agent.tokens_in} / {agent.tokens_out}"
        f"{' (stub: estimated from text length)' if stub else ''} |",
        f"| Model cost (configured price) | {agent.cost} |",
        f"| Tool calls / tool errors | {agent.tool_steps} / {agent.tool_errors} |",
        "",
        "Citation relevance is checked against a fixed map of sections per exception",
        '(`RELEVANT_SECTIONS`). It approximates "the citation supports the decision"; it',
        "does not read the cited text.",
        "",
        "## Manual-queue reasons",
        "",
    ]
    if agent.fail_reasons:
        lines += ["| Reason | Cases |", "|---|---|"]
        lines += [f"| {reason} | {n} |" for reason, n in agent.fail_reasons.items()]
    else:
        lines.append("None.")
    lines += [
        "",
        "## Exception classes (agent)",
        "",
        "| Class | Support | Predicted | Correct |",
        "|---|---|---|---|",
    ]
    for code, entry in agent.per_class.items():
        lines.append(f"| {code} | {entry['support']} | {entry['predicted']} | {entry['correct']} |")
    lines += ["", "## Where the agent is wrong (exception, action or approver)", ""]
    if agent.errors_by_scenario:
        lines += ["| Scenario | Invoices |", "|---|---|"]
        lines += [f"| `{s}` | {n} |" for s, n in agent.errors_by_scenario.items()]
    else:
        lines.append("None.")
    lines.append("")
    return "\n".join(lines)


def write_eval(
    meta: EvalMeta,
    agent: AgentSummary,
    baseline: Summary,
    cases: Sequence[AgentCase],
    report: Path,
    evidence: Path,
) -> None:
    report.parent.mkdir(parents=True, exist_ok=True)
    report.write_text(render_eval_report(meta, agent, baseline), encoding="utf-8", newline="\n")
    evidence.parent.mkdir(parents=True, exist_ok=True)
    evidence.write_text(
        json.dumps(
            {
                "meta": meta.model_dump(mode="json"),
                "agent": agent.model_dump(mode="json"),
                "baseline": baseline.model_dump(mode="json"),
                "cases": [c.model_dump(mode="json") for c in cases],
            },
            indent=2,
            sort_keys=True,
        )
        + "\n",
        encoding="utf-8",
        newline="\n",
    )
