"use client";

import { keepPreviousData, useQuery } from "@tanstack/react-query";
import Link from "next/link";
import { useState } from "react";

import { RiskBadge, StatusBadge } from "@/components/badges";
import { EmptyState, ErrorState, LoadingState, PageHeader, Pagination } from "@/components/common";
import { Card, CardContent } from "@/components/ui/card";
import { Table, TableBody, TableCell, TableHead, TableHeader, TableRow } from "@/components/ui/table";
import { Tabs, TabsList, TabsTrigger } from "@/components/ui/tabs";
import { api, qs } from "@/lib/api";
import { fmtRelative } from "@/lib/format";
import type { Page, PlanSummary } from "@/lib/types";

const FILTERS: Record<string, string | undefined> = {
  all: undefined,
  draft: "DRAFT,ASSESSMENT_COMPLETE,CHANGES_REQUESTED",
  pending: "PENDING_APPROVAL",
  approved: "APPROVED",
  rejected: "REJECTED",
};

export default function RemediationPage() {
  const [tab, setTab] = useState("all");
  const [page, setPage] = useState(1);
  const query = qs({ status: FILTERS[tab], page, page_size: 20 });
  const { data, error, isLoading, refetch } = useQuery({
    queryKey: ["plans", query],
    queryFn: () => api.get<Page<PlanSummary>>(`/plans${query}`),
    placeholderData: keepPreviousData,
  });
  return (
    <>
      <PageHeader title="Remediation plans" description="Evidence-linked proposals generated by the planning agents. Plans never execute anything: approved plans become ServiceNow change requests for human implementers." />
      <Tabs value={tab} onValueChange={(v) => { setTab(v); setPage(1); }} className="mb-3">
        <TabsList>
          <TabsTrigger value="all">All</TabsTrigger>
          <TabsTrigger value="draft">Draft / assessed</TabsTrigger>
          <TabsTrigger value="pending">Pending approval</TabsTrigger>
          <TabsTrigger value="approved">Approved</TabsTrigger>
          <TabsTrigger value="rejected">Rejected</TabsTrigger>
        </TabsList>
      </Tabs>
      <Card>
        <CardContent>
          {isLoading && <LoadingState />}
          {error && <ErrorState error={error} onRetry={refetch} />}
          {data && data.items.length === 0 && <EmptyState title="No plans in this view" description="Start an AI investigation from a finding to generate a plan." />}
          {data && data.items.length > 0 && (
            <>
              <div className="overflow-x-auto">
                <Table>
                  <TableHeader>
                    <TableRow>
                      <TableHead>Plan</TableHead><TableHead>Risk</TableHead><TableHead>Lifecycle</TableHead>
                      <TableHead>Approval</TableHead><TableHead>ServiceNow</TableHead><TableHead>Updated</TableHead>
                    </TableRow>
                  </TableHeader>
                  <TableBody>
                    {data.items.map((p) => (
                      <TableRow key={p.id}>
                        <TableCell className="max-w-md">
                          <Link href={`/remediation/${p.id}`} className="font-medium text-primary hover:underline">{p.title}</Link>
                          <div className="text-xs text-muted-foreground">
                            rev {p.revision} · {p.business_service ?? "no service"} {p.requires_expert_validation && <span className="text-risk-medium">· expert validation required</span>}
                          </div>
                        </TableCell>
                        <TableCell><RiskBadge level={p.risk_level} score={p.risk_score} /></TableCell>
                        <TableCell><StatusBadge status={p.lifecycle_stage} /></TableCell>
                        <TableCell><StatusBadge status={p.approval_state} /></TableCell>
                        <TableCell className="font-mono text-xs">{p.servicenow_number ?? "—"}</TableCell>
                        <TableCell className="text-xs text-muted-foreground">{fmtRelative(p.updated_at)}</TableCell>
                      </TableRow>
                    ))}
                  </TableBody>
                </Table>
              </div>
              <Pagination page={data.page} pageSize={data.page_size} total={data.total} onPage={setPage} />
            </>
          )}
        </CardContent>
      </Card>
    </>
  );
}
