_key_locks: dict[str, threading.Lock] = defaultdict(threading.Lock)
_registry_lock = threading.Lock()

RISK_MAP = {"critical": "2", "high": "2", "medium": "3", "low": "4"}  # ServiceNow: 2 High, 3 Moderate, 4 Low
IMPACT_MAP = {"high": "1", "medium": "2", "low": "3", "unknown": "2"}  # 1 High, 2 Medium, 3 Low


class ChangeRequestPayload(BaseModel):
    """Strict schema for the only change_request fields Aegis is allowed to write."""

    short_description: str = Field(max_length=160)
    description: str = Field(max_length=4000)
    justification: str = Field(max_length=4000)
    implementation_plan: str = Field(max_length=4000)
    backout_plan: str = Field(max_length=4000)
    test_plan: str = Field(max_length=4000)
    risk: str = Field(pattern=r"^[1-4]$")
    impact: str = Field(pattern=r"^[1-3]$")
    type: str = Field(pattern=r"^(normal|standard|emergency)$")
    category: str = Field(max_length=40)
    cmdb_ci: str | None = Field(default=None, max_length=32)
    business_service: str | None = Field(default=None, max_length=32)
    correlation_id: str = Field(max_length=100)
    correlation_display: str = Field(max_length=100)


class ChangeTaskPayload(BaseModel):
    short_description: str = Field(max_length=160)
    description: str = Field(max_length=4000)
    change_request: str = Field(max_length=32)
    cmdb_ci: str | None = Field(default=None, max_length=32)
    correlation_id: str = Field(max_length=100)
    correlation_display: str = Field(max_length=100)


@dataclass
class SyncOutcome:
    ok: bool
    records: list[ServiceNowRecord] = field(default_factory=list)
    error: str | None = None
    gate_reasons: list[str] = field(default_factory=list)
    adopted: bool = False


def _numbered(items: list[Any]) -> str:
    lines = []
    for i, item in enumerate(items, 1):
        text = item.get("step") if isinstance(item, dict) else str(item)
        lines.append(f"{i}. {text}")
    return "\n".join(lines)


def build_change_payload(snapshot: dict[str, Any], key: str) -> ChangeRequestPayload:
    plan, ctx = snapshot["plan"], snapshot["context"]
    asset = ctx.get("asset") or {}
    host = asset.get("hostname", "unresolved asset")
    level = ctx.get("risk_level") or "medium"
    impact = (ctx.get("change_impact") or {}).get("business_impact", "unknown")
    return ChangeRequestPayload(
        short_description=f"[AegisRemediate] Remediate {ctx['cve_id']} on {host}"[:160],
        description=(
            f"{plan['summary']}\n\nRecommended action: {plan['recommended_action']}\n"
            f"Risk score {ctx.get('risk_score')} ({level}, {ctx.get('priority')}). Finding {ctx['finding_id']}.\n"
            "Generated by AegisRemediate AI after human approval."
        )[:4000],
        justification=f"{ctx['cve_id']} assessed as {level} risk ({ctx.get('priority')}). {plan.get('expected_impact', '')}"[
            :4000
        ],
        implementation_plan=_numbered(plan.get("implementation_steps", []))[:4000],
        backout_plan=_numbered(plan.get("rollback_steps", []))[:4000],
        test_plan=_numbered(plan.get("verification_steps", []) + plan.get("testing_requirements", []))[:4000],
        risk=RISK_MAP.get(level, "3"),
        impact=IMPACT_MAP.get(impact, "2"),
        type="normal",
        category="Software",
        cmdb_ci=asset.get("cmdb_sys_id"),
        business_service=asset.get("business_service_sys_id"),
        correlation_id=key,
        correlation_display="AegisRemediate AI",
    )


def build_task_payload(snapshot: dict[str, Any], key: str, change_sys_id: str) -> ChangeTaskPayload:
    plan, ctx = snapshot["plan"], snapshot["context"]
    asset = ctx.get("asset") or {}
    return ChangeTaskPayload(
        short_description=f"Implement remediation for {ctx['cve_id']} on {asset.get('hostname', 'asset')}"[:160],
        description=_numbered(plan.get("implementation_steps", []))[:4000],
        change_request=change_sys_id,
        cmdb_ci=asset.get("cmdb_sys_id"),
        correlation_id=key,
        correlation_display="AegisRemediate AI",
    )


class ServiceNowSyncService:
    def __init__(self, db: Session, client: ServiceNowClient | None = None) -> None:
        self.db = db
        self.client = client or get_servicenow_client()
        self.settings = get_settings()

    # ------------------------------------------------------------------ helpers
    def _attempt(
        self,
        record: ServiceNowRecord | None,
        op: str,
        table: str,
        outcome: str,
        started: float,
        actor: Principal,
        error: str | None = None,
        status: int | None = None,
    ) -> None:
        self.db.add(
            ServiceNowSyncAttempt(
                record_id=record.id if record else None,
                operation=op,
                table_name=table,
                outcome=outcome,
                error=error,
                http_status=status,
                latency_ms=int((time.monotonic() - started) * 1000),
                actor=actor.email,
            )
        )

    def _reserve(
        self, key: str, plan_id: str, approval_id: str, table: str, payload: dict[str, Any], parent_id: str | None = None
    ) -> ServiceNowRecord:
        rec = self.db.scalar(select(ServiceNowRecord).where(ServiceNowRecord.idempotency_key == key))
        if rec is None:
            rec = ServiceNowRecord(
                idempotency_key=key,
                plan_id=plan_id,
                approval_request_id=approval_id,
                parent_record_id=parent_id,
                mode=self.client.mode,
                instance=self.client.instance_label,
                table_name=table,
                sync_state=SyncState.SYNC_PENDING,
                payload=payload,
            )
            self.db.add(rec)
            try:
                self.db.commit()
            except IntegrityError:
                self.db.rollback()
                rec = self.db.scalar(select(ServiceNowRecord).where(ServiceNowRecord.idempotency_key == key))
                assert rec is not None
        return rec

    def _push(self, rec: ServiceNowRecord, payload: dict[str, Any], actor: Principal) -> bool:
        """Reconcile-then-create for one record. Returns True when the remote record exists."""
        if rec.sync_state == SyncState.SYNCED and rec.sys_id:
            return True
        rec.attempts += 1
        self.db.commit()  # never hold a transaction across remote I/O
        started = time.monotonic()
        try:
            existing = self.client.query(rec.table_name, f"correlation_id={rec.idempotency_key}", None, 2)
            if existing:
                remote, outcome = existing[0], "adopted_existing"
            else:
                remote, outcome = self.client.create(rec.table_name, payload), "success"
        except ServiceNowError as exc:
            rec.sync_state = SyncState.SYNC_FAILED
            rec.last_error = f"{type(exc).__name__}: {exc}"[:1000]
            if exc.outcome_unknown:
                rec.last_error += " (outcome unknown - next retry reconciles by correlation_id before creating)"
            self._attempt(rec, "create", rec.table_name, "error", started, actor, rec.last_error, exc.status)
            record_audit(
                self.db,
                actor=actor,
                action="servicenow_sync_failed",
                target_type="servicenow_record",
                target_id=rec.id,
                details={"table": rec.table_name, "error": rec.last_error},
                outcome="error",
            )
            self.db.commit()
            return False
        rec.sys_id, rec.number = remote.get("sys_id"), remote.get("number")
        rec.record_url = self.client.record_url(rec.table_name, rec.sys_id) if rec.sys_id else None
        rec.sync_state, rec.last_error, rec.last_sync_at = SyncState.SYNCED, None, utcnow()
        rec.external_state = str(remote.get("state")) if remote.get("state") is not None else None
        self._attempt(rec, "create", rec.table_name, outcome, started, actor)
        record_audit(
            self.db,
            actor=actor,
            action="servicenow_record_created" if outcome == "success" else "servicenow_record_adopted",
            target_type="servicenow_record",
            target_id=rec.id,
            new_state={"sys_id": rec.sys_id, "number": rec.number, "table": rec.table_name, "mode": rec.mode},
            details={"idempotency_key": rec.idempotency_key},
        )
        self.db.commit()
        return True

    # ------------------------------------------------------------------ public API
    def sync_approved_plan(self, approval_request_id: str, actor: Principal) -> SyncOutcome:
        req = self.db.get(ApprovalRequest, approval_request_id)
        if req is None:
            return SyncOutcome(False, error="approval request not found")
        change_table = self.settings.servicenow_change_table
        task_table = remediation_table()
        tables = {change_table} | ({task_table} if task_table else set())
        key_base = f"aegis-{approval_request_id}"
        with _registry_lock:
            lock = _key_locks[key_base]
        with lock:
            gate = authorize_write(self.db, approval_request_id, tables, actor)
            if not gate.allowed:
                self._attempt(None, "create", change_table, "denied", time.monotonic(), actor, "; ".join(gate.reasons))
                self.db.commit()
                return SyncOutcome(False, error="write gate denied", gate_reasons=gate.reasons)
            snapshot = gate.snapshot or {}
            change_payload = build_change_payload(snapshot, f"{key_base}-change").model_dump(exclude_none=True)
            change = self._reserve(f"{key_base}-change", req.plan_id, req.id, change_table, change_payload)
            records = [change]
            if not self._push(change, change_payload, actor):
                return SyncOutcome(False, records, change.last_error)
            if task_table:
                task_payload = build_task_payload(snapshot, f"{key_base}-task", change.sys_id or "").model_dump(exclude_none=True)
                task = self._reserve(f"{key_base}-task", req.plan_id, req.id, task_table, task_payload, change.id)
                records.append(task)
                if not self._push(task, task_payload, actor):
                    return SyncOutcome(False, records, task.last_error)
            return SyncOutcome(True, records)

    def refresh_status(self, record: ServiceNowRecord, actor: Principal) -> ServiceNowRecord:
        """Read-only status synchronisation (never closes findings - verification does)."""
        if not record.sys_id:
            return record
        started = time.monotonic()
        try:
            remote = self.client.get(record.table_name, record.sys_id)
        except ServiceNowError as exc:
            record.last_error = f"status refresh failed: {exc}"[:1000]
            self._attempt(record, "read", record.table_name, "error", started, actor, record.last_error, exc.status)
            return record
        self._attempt(record, "read", record.table_name, "success", started, actor)
        if remote is None:
            record.last_error = "remote record no longer exists"
            return record
        previous = record.external_state
        record.external_state = str(remote.get("state"))
        record.external_close_code = remote.get("close_code") or None
        record.last_sync_at = utcnow()
        record.last_error = None
        plan = self.db.get(RemediationPlan, record.plan_id)
        if plan is not None and record.parent_record_id is None:
            state = record.external_state
            target = None
            if state in ("-2", "-1", "0"):
                target = RemediationState.REMEDIATION_IN_PROGRESS
            elif state == "3" and (record.external_close_code or "").lower().startswith("successful"):
                target = RemediationState.IMPLEMENTED
            elif state == "4":
                target = RemediationState.CANCELLED
            if target and plan.remediation_state != target and plan.remediation_state != RemediationState.IMPLEMENTED:
                record_audit(
                    self.db,
                    actor=actor,
                    action="remediation_state_synced",
                    target_type="remediation_plan",
                    target_id=plan.id,
                    previous_state={"remediation_state": plan.remediation_state},
                    new_state={"remediation_state": target, "servicenow_state": state_label(record)},
                )
                plan.remediation_state = target
        if previous != record.external_state:
            log.info("servicenow state changed", extra={"record": record.number, "from": previous, "to": record.external_state})
        return record


def state_label(record: ServiceNowRecord) -> str | None:
    if record.external_state is None:
        return None
    states = CHANGE_STATES if record.table_name == "change_request" else TASK_STATES
    return states.get(record.external_state, record.external_state)
