"""Idempotent, approval-gated ServiceNow synchronisation.

Algorithm (per record, keyed by a deterministic idempotency key derived from the approval):

1. Gate: ``authorize_write`` must allow the write (re-checked on every attempt).
2. Reserve: insert/lock the local ``servicenow_records`` row (unique idempotency key) and
   commit *before* any network call - no DB transaction is held across remote I/O.
3. Reconcile: query the remote table for ``correlation_id = <key>``. If a record exists
   (e.g. a previous attempt's response was lost), adopt it instead of creating another.
4. Create, then persist ``sys_id``/``number``. Failures mark ``SYNC_FAILED`` with the error;
   retries repeat from step 1 and can never create duplicates.
"""

