FORBIDDEN_IN_OUTPUT = ("query_selector", "querySelector", "xpath", "$(", "css=", "document.querySelector")


def _render_step(action: RecordedAction) -> str:
    # 12 spaces: steps live inside with-playwright -> try: in the template.
    if action.kind == "click":
        if not action.role or not action.name:
            raise ValueError(f"click needs role+name: {action}")
        return f'            page.get_by_role("{action.role}", name="{action.name}").click()'
    if action.kind == "fill":
        if not action.role or not action.name:
            raise ValueError(f"fill needs role+name: {action}")
        return f'            page.get_by_role("{action.role}", name="{action.name}").fill("{action.value}")'
    if action.kind == "expect_title":
        return f'            assert page.title() == "{action.value}", f"title was {{page.title()!r}}"'
    if action.kind == "expect_text":
        return f'            expect(page.get_by_text("{action.value}")).to_be_visible(timeout=15000)'
    raise ValueError(f"Unknown action kind {action.kind!r}")


