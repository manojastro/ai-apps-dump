"""Test writer: confirmed real_bug -> standalone Playwright test + GitHub PR.

Two halves, split at the RecordedAction contract:
1. Deterministic (this module, tested offline): render RecordedActions into a
   runnable script, with guards enforced in code — valid Python (ast.parse),
   intent-only location (get_by_role; any CSS/XPath/query_selector rejected),
   bug key embedded. The rendered script is executed against broken vs fixed
   fixture pages in tests to prove fail-then-pass.
2. LLM prose->actions translation + live `gh` PR delivery need the model key
   and repo token — `write_regression_test` raises until then.

The agent never merges; delivery opens a PR for human review.
"""

